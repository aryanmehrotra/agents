#!/usr/bin/env python3
"""Pattern-separation / near-duplicate density over the org-memory corpus.

Deterministic and stdlib-only: given the same corpus this prints the same numbers, so the report it
backs is reproducible rather than a transcript of an ad-hoc session. That property is the reason this
file exists. The first run of this check was done inline, and its theme table shipped a row reading
"idempotent | substring 16 | word-bnd 0" -- a word-boundary count can never be zero when the substring
count is 16, since every word-boundary match is also a substring match. Nobody could see the defect
because there was no code to look at, and the intra-theme duplicate check for that theme silently
examined an empty set. A committed script makes that class of error reviewable.

Usage:
    python3 dedup_density.py [--url http://localhost:8000] [--corpus corpus.json]
"""

import argparse
import difflib
import hashlib
import json
import re
import sys
import urllib.request
from collections import defaultdict

# Linking thresholds. A pair is "near-duplicate" when either fires -- ratio catches reworded
# restatements, Jaccard catches reordered ones.
RATIO_MIN = 0.7
JACCARD_MIN = 0.6

# Themes probed for intra-theme restatement. Each entry is (label, regex-alternation of word stems).
THEMES = [
    ("retry", r"retry|retries|retried|retrying"),
    ("aggregator", r"aggregator|aggregators"),
    ("idempotent", r"idempotent|idempotency|idempotence"),
    ("FINAL", r"FINAL"),
    ("timezone", r"timezone|timezones|tz"),
    ("clickhouse", r"clickhouse"),
]

STOP = {
    "the", "a", "an", "and", "or", "of", "to", "in", "for", "on", "is", "are", "be", "with", "as",
    "at", "by", "it", "its", "not", "no", "so", "that", "this", "from", "we", "use", "used", "using",
}


def fetch(url, corpus):
    """Load decisions from the live service, falling back to a corpus snapshot."""
    if corpus:
        with open(corpus) as fh:
            raw = json.load(fh)
    else:
        with urllib.request.urlopen(f"{url}/decisions", timeout=60) as resp:
            raw = json.load(resp)["data"]

    rows = raw["decisions"] if isinstance(raw, dict) else raw
    out = []

    for row in rows:
        d = row.get("decision", row)
        if d.get("quarantined") or d.get("superseded_by"):
            continue  # only surfaceable decisions can be redundant in recall
        out.append({"id": d["id"], "what": d.get("what", ""), "why": d.get("why", "")})

    return out


def tokens(text):
    return {t for t in re.findall(r"[a-z0-9_]+", text.lower()) if t not in STOP and len(t) > 2}


def jaccard(a, b):
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def families(decisions):
    """Union-find over candidate pairs generated by an inverted-index blocking pass."""
    toks = {d["id"]: tokens(d["what"]) for d in decisions}

    index = defaultdict(list)
    for d in decisions:
        for t in toks[d["id"]]:
            index[t].append(d["id"])

    # Blocking: only compare decisions sharing a non-ubiquitous token. Ubiquitous tokens generate
    # O(n^2) useless pairs and no signal, so cap the posting list length.
    cap = max(2, len(decisions) // 20)
    candidates = set()

    for postings in index.values():
        if len(postings) > cap:
            continue
        for i, a in enumerate(postings):
            for b in postings[i + 1:]:
                candidates.add((a, b) if a < b else (b, a))

    what = {d["id"]: d["what"] for d in decisions}
    parent = {d["id"]: d["id"] for d in decisions}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    linked = []

    for a, b in sorted(candidates):
        j = jaccard(toks[a], toks[b])
        r = difflib.SequenceMatcher(None, what[a], what[b]).ratio()

        if r > RATIO_MIN or j >= JACCARD_MIN:
            linked.append((a, b, round(r, 3), round(j, 3)))
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[ra] = rb

    groups = defaultdict(list)
    for d in decisions:
        groups[find(d["id"])].append(d["id"])

    return [g for g in groups.values() if len(g) >= 2], linked


def theme_table(decisions):
    """Substring vs word-boundary counts per theme, over `what` + `why`.

    The word-boundary count is the honest one: a bare substring count for "tz" also matches "utc",
    "quartz" and "blitz". Both are printed so the gap between them is visible instead of asserted --
    and so a word-boundary count of 0 alongside a non-zero substring count is immediately obviously
    a bug rather than a finding.
    """
    rows = []

    for label, stems in THEMES:
        sub_re = re.compile(stems, re.I)
        word_re = re.compile(rf"\b(?:{stems})\b", re.I)

        sub_hits, word_hits = [], []

        for d in decisions:
            blob = f"{d['what']} {d['why']}"
            if sub_re.search(blob):
                sub_hits.append(d["id"])
            if word_re.search(blob):
                word_hits.append(d["id"])

        assert len(word_hits) <= len(sub_hits), f"{label}: word-boundary count exceeds substring count"

        if sub_hits and not word_hits:
            raise AssertionError(
                f"{label}: {len(sub_hits)} substring hits but 0 word-boundary hits -- "
                "impossible, the word-boundary pattern is broken"
            )

        rows.append((label, len(sub_hits), len(word_hits), intra_dups(decisions, word_hits)))

    return rows


def intra_dups(decisions, ids):
    """Count near-duplicate pairs WITHIN a theme -- restatements of one rule, not topical breadth."""
    by_id = {d["id"]: d["what"] for d in decisions}
    members = [i for i in ids if i in by_id]
    pairs, best = 0, 0.0

    for i, a in enumerate(members):
        for b in members[i + 1:]:
            r = difflib.SequenceMatcher(None, by_id[a], by_id[b]).ratio()
            best = max(best, r)
            if r > RATIO_MIN:
                pairs += 1

    total = len(members) * (len(members) - 1) // 2

    return f"{pairs}/{total} (closest {best:.2f})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://localhost:8000")
    ap.add_argument("--corpus", default=None)
    args = ap.parse_args()

    decisions = fetch(args.url, args.corpus)
    n = len(decisions)

    # Pin the exact corpus these numbers describe, so a later re-run can prove it measured the same
    # thing instead of quietly drifting (the corpus grew by one decision between the first validation
    # sweep and its audit, and nothing in either report could have detected that).
    digest = hashlib.sha256(
        "\n".join(f"{d['id']}\t{d['what']}" for d in sorted(decisions, key=lambda x: x["id"])).encode()
    ).hexdigest()[:16]

    fams, linked = families(decisions)
    redundant = sum(len(f) - 1 for f in fams)

    print(f"corpus:            {n} surfaceable decisions")
    print(f"corpus_sha256_16:  {digest}")
    print(f"near-dup families: {len(fams)} (sizes: {sorted((len(f) for f in fams), reverse=True)})")
    print(f"decisions in one:  {sum(len(f) for f in fams)} ({sum(len(f) for f in fams) / n * 100:.1f}%)")
    print(f"redundant:         {redundant} ({redundant / n * 100:.1f}% redundancy)")
    print()
    print(f"{'theme':<12} {'substring':>10} {'word-bnd':>10}  intra-dup pairs (ratio>0.7)")

    for label, sub, word, dups in theme_table(decisions):
        print(f"{label:<12} {sub:>10} {word:>10}  {dups}")

    print()
    print("largest families:")
    what = {d["id"]: d["what"] for d in decisions}

    for fam in sorted(fams, key=len, reverse=True)[:5]:
        print(f"  size {len(fam)}")
        for i in fam:
            print(f"    {i}: {what[i][:88]}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
